const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8').replace(/^\uFEFF/, ''));
const version = read('config/app-version.json').version;
if (!/^\d+\.\d+\.\d+\.\d+$/.test(version)) throw new Error('版本必须为四段数字，例如 0.0.3.1');
const resourceVersion = version.split('.').slice(0, 3).join('.');
const write = (file, text) => fs.writeFileSync(path.join(root, file), text);
write('assets/scripts/core/AppVersion.ts', `// Generated by tools/sync-app-version.cjs; edit config/app-version.json.\nexport const APP_VERSION = '${version}';\nexport const RESOURCE_VERSION = '${resourceVersion}';\n`);
write('build-templates/bytedance-mini-game/app-version.js', `// Generated by tools/sync-app-version.cjs; edit config/app-version.json.\nmodule.exports = { version: '${version}', resourceVersion: '${resourceVersion}' };\n`);
const pkg = read('package.json');
pkg.version = version;
pkg.scripts = { ...pkg.scripts, 'version:sync': 'node tools/sync-app-version.cjs', 'test:version': 'node tools/test-app-version.cjs' };
write('package.json', JSON.stringify(pkg, null, 2) + '\n');
// Update future build options, never rewrite historical successful task records.
for (const file of ['profiles/v2/packages/builder.json', 'profiles/v2/packages/bytedance-mini-game.json']) {
    const config = read(file);
    const common = config.builder ? config.builder.common : config.common;
    if (common && common.platform === 'bytedance-mini-game') {
        common.md5Cache = true;
        write(file, JSON.stringify(config, null, 2) + '\n');
    }
}
console.log(`应用版本 ${version}，资源版本 ${resourceVersion}；已同步 FooterEnv、抖音启动配置并开启 MD5，保留原资源服务器地址。`);
